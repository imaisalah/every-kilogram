// Orbit validation: recompute every orbit in the game from first principles, with constants
// typed in here from the NASA NSSDC planetary fact sheets (not read from the game), and
// compare period and time-in-shadow with what the game uses. Also checks three real
// missions whose orbital periods NASA publishes.
//   node tools/validate-orbits.mjs            prints the report
//   node tools/validate-orbits.mjs --write    also writes docs/VALIDATION.md
//
// What this is: a check that the game's two-body orbit maths is implemented correctly and
// lands on real-mission numbers. It is not a GMAT run. docs/gmat/ has a GMAT script for
// the same cases so you can confirm them with NASA's own tool.
import { createRequire } from 'node:module';
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
const require = createRequire(import.meta.url);
globalThis.SMD = {};
require('../js/team/data.js');
const sim = require('../js/team/sim.js');
const P = require('../js/physics.js');

// NSSDC planetary fact sheets: gravitational parameter (km^3/s^2) and mean equatorial radius (km).
const REF = {
  earth: { mu: 398600.4418, r: 6378.137 },
  moon: { mu: 4902.8, r: 1737.4 },
  mars: { mu: 42828.37, r: 3396.2 },
  venus: { mu: 324858.6, r: 6051.8 },
  europa: { mu: 3202.7, r: 1560.8 },
};
const period = (a, mu) => (2 * Math.PI * Math.sqrt((a * a * a) / mu)) / 60; // minutes
// Fraction of a circular orbit spent in the planet's shadow (cylindrical shadow, Sun in the orbit plane: worst case).
const shadow = (a, r) => Math.asin(Math.min(1, r / a)) / Math.PI;

const rows = [];
for (const sc of sim.scenarios()) {
  const d = sim.newDesign(sc.id, 'engineer');
  const cat = sim.catalog(sc.id, 'engineer');
  const orbits = [].concat(...Object.values(cat.roles)).find((s) => s.key === 'orbit').options;
  for (const o of orbits) {
    const x = sim._derive({ ...d, picks: { ...d.picks, orbit: o.id } });
    const ref = REF[o.body];
    if (!ref) continue;
    const rp = ref.r + o.altKm;
    const ra = o.apoKm ? ref.r + o.apoKm : rp;
    const a = (rp + ra) / 2;
    const tRef = period(a, ref.mu);
    const eRef = shadow(a, ref.r) * (o.apoKm ? 0.7 : 1);
    const special = !!(o.periodMinOverride || o.periodDaysOverride || o.eclipseOverride !== undefined);
    rows.push({ scenario: sc.id, orbit: o.name, body: o.body, special, tGame: x.orb.periodMin, tRef, eGame: x.orb.eclipse, eRef, dT: (x.orb.periodMin / tRef - 1) * 100, dE: (x.orb.eclipse - eRef) * 100 });
  }
}

// Real missions with a published orbital period (NASA / USGS fact pages).
const REAL = [
  { name: 'Landsat 9, 705 km sun-synchronous', body: 'earth', alt: 705, publishedMin: 99 },
  { name: 'International Space Station, about 410 km', body: 'earth', alt: 410, publishedMin: 92.7 },
  { name: 'Mars Reconnaissance Orbiter, 255 x 320 km (mean height used)', body: 'mars', alt: 287.5, publishedMin: 112 },
];
const real = REAL.map((m) => {
  const ref = REF[m.body];
  const t = period(ref.r + m.alt, ref.mu);
  return { ...m, t, dPct: (t / m.publishedMin - 1) * 100 };
});

const num = (x, d = 1) => (Number.isFinite(x) ? x.toFixed(d) : '-');
const normal = rows.filter((r) => !r.special);
const worstT = Math.max(...normal.map((r) => Math.abs(r.dT)));
const worstE = Math.max(...normal.map((r) => Math.abs(r.dE)));

let md = `# Orbit validation\n\nGenerated by \`node tools/validate-orbits.mjs --write\`. Constants are typed into the script from the NASA NSSDC planetary fact sheets, not read from the game.\n\n`;
md += `**What this shows:** the game's period and shadow time match an independent two-body calculation for every orbit that uses the standard formulas (${normal.length} orbits; worst period difference ${num(worstT, 2)}%, worst shadow difference ${num(worstE, 2)} percentage points). The small differences come from the game using mean planet radii. **What it does not show:** a GMAT run. See \`docs/gmat/\` to confirm the same cases with NASA's own tool.\n\n`;
md += `## Every orbit in the game\n\n| Mission | Orbit | Period (game, min) | Period (check, min) | Diff % | Shadow (game) | Shadow (check) | Note |\n|---|---|---|---|---|---|---|---|\n`;
for (const r of rows) md += `| ${r.scenario} | ${r.orbit} | ${num(r.tGame)} | ${num(r.tRef)} | ${num(r.dT, 2)} | ${num(r.eGame * 100, 1)}% | ${num(r.eRef * 100, 1)}% | ${r.special ? 'set by hand in the game (tour, tuned or fixed value)' : ''} |\n`;
md += `\n## Real missions with a published period\n\nThe published periods below are from NASA and USGS fact pages as we remember them. **Re-check each against its page before quoting it.**\n\n| Mission | Published (min) | Computed (min) | Diff % |\n|---|---|---|---|\n`;
for (const m of real) md += `| ${m.name} | ${num(m.publishedMin)} | ${num(m.t)} | ${num(m.dPct, 1)} |\n`;
md += `\nEuropa orbits (the flyby tour and low Europa orbit) are not checked here: the tour is a sequence of flybys, not one orbit.\n\n"Shadow" is the share of each orbit spent in the planet's shadow when the Sun lies in the orbit plane, the worst case. Real orbits that are tilted toward the Sun spend less time in shadow.\n`;

console.log(md);
if (process.argv.includes('--write')) {
  const out = path.join(path.dirname(fileURLToPath(import.meta.url)), '..', 'docs', 'VALIDATION.md');
  writeFileSync(out, md);
  console.error('wrote', out);
}
process.exitCode = worstT > 1.5 || worstE > 2 ? 1 : 0;
